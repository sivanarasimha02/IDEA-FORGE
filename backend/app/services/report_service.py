from datetime import datetime
from sqlalchemy.orm import Session
from app.models.farm import Farm
from app.services.weather_service import weather_service
from app.services.satellite_service import satellite_service
from app.services.risk_service import risk_service
from app.services.yield_service import yield_service
from app.services.recommendation_service import recommendation_service
from app.schemas.farm import FarmResponse
from app.schemas.report import FarmReportResponse

class ReportService:
    @staticmethod
    def generate_comprehensive_report(farm: Farm, db: Session) -> FarmReportResponse:
        weather_sum = weather_service.sync_farm_weather(farm, db)
        sat_sum = satellite_service.sync_farm_satellite_data(farm, db)
        risks = risk_service.evaluate_farm_risks(farm, db)
        yield_pred = yield_service.predict_farm_yield(farm, db)
        recs = recommendation_service.generate_farm_recommendations(farm, db)

        return FarmReportResponse(
            generated_at=datetime.utcnow(),
            farm=FarmResponse.model_validate(farm),
            weather_summary=weather_sum,
            satellite_summary=sat_sum,
            climate_risks=risks,
            yield_prediction=yield_pred,
            recommendations=recs,
            disclaimer=(
                "This report is generated by the Predictive Climate & Micro-Location Yield Engine. "
                "All analytical indicators, risk probabilities, and yield estimates are decision-support outputs "
                "grounded in verified remote sensing and agrometeorological models. "
                "Field decisions should be calibrated with qualified agronomic advisors."
            ),
            export_format="json"
        )

report_service = ReportService()
